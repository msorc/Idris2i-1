# Generates UnboxedBits.idr: python3 gen.py > UnboxedBits.idr
import sys
T = [  # tag, idris type, values, width, signed
 ("B8","Bits8",[0,1,2,7,8,9,127,128,200,255],8,False),
 ("B16","Bits16",[0,1,15,16,17,255,32767,32768,65535],16,False),
 ("B32","Bits32",[0,1,31,32,33,65535,2**31-1,2**31,2**32-1],32,False),
 ("B64","Bits64",[0,1,63,64,65,2**32-1,2**32,2**63-1,2**63,2**64-1,0x9e3779b97f4a7c15],64,False),
 ("I8","Int8",[0,1,-1,7,8,9,127,-128,-100],8,True),
 ("I16","Int16",[0,1,-1,15,16,17,32767,-32768,-12345],16,True),
 ("I32","Int32",[0,1,-1,31,32,33,2**31-1,-2**31,123456789],32,True),
 ("I64","Int64",[0,1,-1,63,64,65,2**31,2**32,2**63-1,-2**63,-0x123456789abcdef],64,True),
 ("I","Int",[0,1,-1,63,64,65,2**31,2**32,2**63-1,-2**63,-0x123456789abcdef],64,True),
]
bin_ops = ["add","sub","mul","div","mod","and","or","xor","shl","shr"]
cmp_ops = ["lt","lte","eq","gte","gt"]
prim = {"add":"add","sub":"sub","mul":"mul","div":"div","mod":"mod","and":"and","or":"or","xor":"xor","shl":"shl","shr":"shr",
        "lt":"lt","lte":"lte","eq":"eq","gte":"gte","gt":"gt"}
out = []
w = out.append
w("""-- Generated by gen.py (`python3 gen.py > UnboxedBits.idr`): every operation on
-- the fixed width integers, in functions whose parameters RefC keeps in C
-- integers, on boundary values.  The expected output is that of the Chez
-- backend, without a shift of a signed type by a negative count and the
-- negation of the smallest value, where Chez gives values out of range.
module Main

import Data.List
import Data.String

%default partial

lit : Show a => a -> String
lit = show

b : Int -> String
b 0 = "0"
b _ = "1"

-- (%noinline: the operations are compiled in these functions, on their
-- parameters, not folded or inlined into `main`)
""")
def lits(tag, vals):
    return "[" + ", ".join(("(%d)" % v) if v < 0 else str(v) for v in vals) + "]"
for tag, ty, vals, wid, sg in T:
    for op in bin_ops:
        w("%%noinline\n%s_%s : %s -> %s -> %s\n%s_%s x y = prim__%s_%s x y\n" % (op, tag, ty, ty, ty, op, tag, prim[op], ty))
    for op in cmp_ops:
        w("%%noinline\n%s_%s : %s -> %s -> Int\n%s_%s x y = prim__%s_%s x y\n" % (op, tag, ty, ty, op, tag, prim[op], ty))
    w("%%noinline\nneg_%s : %s -> %s\nneg_%s x = prim__negate_%s x\n" % (tag, ty, ty, tag, ty))
    # with literals
    big = max(vals)
    w("%%noinline\nlits_%s : %s -> List %s\nlits_%s x = [x + %d, x * %d, prim__and_%s x %d, prim__xor_%s x %d, prim__shl_%s x 3, prim__shr_%s x 1, prim__sub_%s %d x]\n"
      % (tag, ty, ty, tag, big, big - 2 if big > 3 else 3, ty, big, ty, (big // 3), ty, ty, ty, big))
    # case on literals
    w("%%noinline\ncase_%s : %s -> Int\ncase_%s x = case x of\n" % (tag, ty, tag))
    for k, v in enumerate(vals):
        w("  %s => %d" % (("(%d)" % v) if v < 0 else str(v), k))
    w("  _ => -1\n")
    # loop: a hash with all operations, in a function that calls itself
    w("""%%noinline
loop_%s : %s -> %s -> Int -> %s
loop_%s acc x 0 = acc
loop_%s acc x n =
  let a = prim__xor_%s (prim__mul_%s acc %d) x
      s = prim__shr_%s a 3
      c = if prim__lt_%s a x == 1 then prim__add_%s a s else prim__sub_%s a s in
      loop_%s c (prim__add_%s x 1) (n - 1)
""" % (tag, ty, ty, ty, tag, tag, ty, ty, 31, ty, ty, ty, ty, tag, ty))
# casts between all
for tag, ty, vals, wid, sg in T:
    for tag2, ty2, _, _, _ in T:
        if ty2 == ty: continue
        w("%%noinline\ncast_%s_%s : %s -> %s\ncast_%s_%s x = prim__cast_%s%s x\n" % (tag, tag2, ty, ty2, tag, tag2, ty, ty2))
    w("%%noinline\ncast_%s_BI : %s -> Integer\ncast_%s_BI x = prim__cast_%sInteger (prim__add_%s x 0)\n" % (tag, ty, tag, ty, ty))
    w("%%noinline\ncast_%s_D : %s -> Double\ncast_%s_D x = prim__cast_%sDouble (prim__add_%s x 0)\n" % (tag, ty, tag, ty, ty))
    w("%%noinline\ncast_%s_C : %s -> Char\ncast_%s_C x = prim__cast_%sChar (prim__add_%s x 0)\n" % (tag, ty, tag, ty, ty))
    w("%%noinline\ncast_BI_%s : Integer -> %s\ncast_BI_%s x = prim__add_%s (prim__cast_Integer%s x) 0\n" % (tag, ty, tag, ty, ty))
    w("%%noinline\ncast_D_%s : Double -> %s\ncast_D_%s x = prim__add_%s (prim__cast_Double%s x) 0\n" % (tag, ty, tag, ty, ty))
    w("%%noinline\ncast_C_%s : Char -> %s\ncast_C_%s x = prim__add_%s (prim__cast_Char%s x) 0\n" % (tag, ty, tag, ty, ty))

integers = [0, -1, 1, 255, 256, -129, 2**31, 2**63, 2**64 + 5, -(2**64) - 7, 10**30 + 12345, -(10**25)]
doubles = ["0.0", "-1.5", "255.9", "-128.7", "65536.25", "1.0e10", "-1.0e10", "4.0e18", "-9.0e18"]
chars = ["'a'", "'\\0'", "'\\xff'", "'\\x10FFFF'", "'\\x3bb'", "'\\x1F600'"]

w("""-- The values come from lists, at run time.
main : IO ()
main = do""")
for tag, ty, vals, wid, sg in T:
    w("  let vs : List %s = %s" % (ty, lits(tag, vals)))
    ops = " ++ \" \" ++ ".join(["lit (%s_%s x y)" % (op, tag) for op in ["add","sub","mul","and","or","xor","shl"]])
    # shr on signed by negative count differs on Chez: avoid
    shr = "(if %s then \"-\" else lit (shr_%s x y))" % (("y < 0" if sg else "False"), tag)
    dm = "(if y == 0 then \"- -\" else lit (div_%s x y) ++ \" \" ++ lit (mod_%s x y))" % (tag, tag)
    cmps = " ++ ".join(["b (%s_%s x y)" % (op, tag) for op in cmp_ops])
    w("  for_ vs $ \\x => for_ vs $ \\y => putStrLn (\"%s \" ++ show x ++ \" \" ++ show y ++ \": \" ++ %s ++ \" \" ++ %s ++ \" \" ++ %s ++ \" \" ++ %s)"
      % (tag, ops, shr, dm, cmps))
    negx = "(if x == %d then \"-\" else lit (neg_%s x))" % (-(2**(wid-1)), tag) if sg else "lit (neg_%s x)" % tag
    w("  for_ vs $ \\x => putStrLn (\"%s \" ++ show x ++ \": \" ++ %s ++ \" \" ++ show (lits_%s x) ++ \" \" ++ show (case_%s x) ++ \" \" ++ lit (loop_%s x x 1000))"
      % (tag, negx, tag, tag, tag))
    casts = " ++ \" \" ++ ".join(["show (cast_%s_%s x)" % (tag, t2) for t2, ty2, _, _, _ in T if ty2 != ty])
    w("  for_ vs $ \\x => putStrLn (\"%s \" ++ show x ++ \" casts: \" ++ %s ++ \" \" ++ show (cast_%s_BI x) ++ \" \" ++ show (cast_%s_D x) ++ \" \" ++ show (ord (cast_%s_C x)))"
      % (tag, casts, tag, tag, tag))
w("  let is : List Integer = [%s]" % ", ".join("(%d)" % v for v in integers))
w("  let ds : List Double = [%s]" % ", ".join("(%s)" % v for v in doubles))
w("  let cs : List Char = [%s]" % ", ".join(chars))
for tag, ty, vals, wid, sg in T:
    w("  putStrLn (\"%s from Integer: \" ++ show (map cast_BI_%s is))" % (tag, tag))
    w("  putStrLn (\"%s from Double: \" ++ show (map cast_D_%s ds))" % (tag, tag))
    w("  putStrLn (\"%s from Char: \" ++ show (map cast_C_%s cs))" % (tag, tag))
print("\n".join(out))
